    def mcp_example_content(project_directory, type)
      path = case type
      when :codex
        File.join(File.expand_path(project_directory), '.claude', 'mcps', 'codex-mcp.example.toml')
      when :claude
        File.join(File.expand_path(project_directory), '.claude', 'mcps', 'claude-mcp.example.json')
      end

      return File.read(path) if path && File.exist?(path)

      type == :claude ? CLAUDE_MCP_EXAMPLE : MCP_EXAMPLE
    end

    def write_file(path, content, force:)
      if File.exist?(path) && !force
        puts "#{relative(path)} [exists]"
        return
      end

      FileUtils.mkdir_p(File.dirname(path))
      File.write(path, content)
      puts "#{relative(path)} [written]"
    end

    def write_executable(path, content, force:)
      write_file(path, content, force: force)
      FileUtils.chmod('+x', path) if File.exist?(path)
    end

    def print_file_status(path, label)
      status = File.exist?(path) ? 'ok' : 'missing'
      puts "#{label} [#{status}] #{path}"
    end

    def print_command_status(command)
      path = find_command(command)
      if path
        puts "#{command} [ok] #{path}"
      else
        puts "#{command} [missing]"
      end
    end

    def find_command(command)
      ENV.fetch('PATH', '').split(File::PATH_SEPARATOR).each do |dir|
        path = File.join(dir, command)
        return path if File.executable?(path) && !File.directory?(path)
      end
      nil
    end

    def relative(path)
      root = Dir.pwd
      expanded = File.expand_path(path)
      expanded.start_with?(root + File::SEPARATOR) ? expanded[(root.length + 1)..] : expanded
    end

    def abort_with(message)
      warn message
      exit 1
    end
  end
