    CODEGRAPH_INIT_SCRIPT = <<~'SH'
      #!/bin/sh

      set -eu

      SCRIPT_DIR="$(CDPATH= cd -- "$(dirname "$0")" && pwd)"
      PROJECT_ROOT="${PODX_AI_PROJECT_ROOT:-$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)}"
      CODEGRAPH_BIN="${CODEGRAPH_BIN:-$SCRIPT_DIR/codegraph.sh}"
      CODE_REVIEW_GRAPH_BIN="${CODE_REVIEW_GRAPH_BIN:-code-review-graph}"

      run_codegraph() {
        if [ -x "$CODEGRAPH_BIN" ]; then
          "$CODEGRAPH_BIN" "$@"
        elif command -v npx >/dev/null 2>&1; then
          npx -y @colbymchenry/codegraph "$@"
        else
          echo "warning: 未找到 codegraph，也未找到 npx，跳过 CodeGraph。"
          return 0
        fi
      }

      echo "==> 初始化 CodeGraph"
      run_codegraph init "$PROJECT_ROOT" || true
      run_codegraph index "$PROJECT_ROOT" || true
      run_codegraph status "$PROJECT_ROOT" || true

      echo
      echo "==> 初始化 Code Review Graph"
      if command -v "$CODE_REVIEW_GRAPH_BIN" >/dev/null 2>&1; then
        (cd "$PROJECT_ROOT" && "$CODE_REVIEW_GRAPH_BIN" build)
      else
        echo "warning: 未找到 code-review-graph，跳过 Code Review Graph。"
        echo "         可安装后设置 CODE_REVIEW_GRAPH_BIN=/path/to/code-review-graph 再执行。"
      fi

      echo
      echo "==> 完成"
      echo "Project: $PROJECT_ROOT"
    SH

