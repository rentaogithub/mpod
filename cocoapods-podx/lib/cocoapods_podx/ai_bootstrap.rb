    HERMES_MCP_SCRIPT = <<~'SH'
      #!/bin/sh

      set -eu

      SCRIPT_DIR="$(CDPATH= cd -- "$(dirname "$0")" && pwd)"
      PROJECT_ROOT="${PODX_AI_PROJECT_ROOT:-$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)}"
      HERMES_BIN="${HERMES_BIN:-$HOME/.local/bin/hermes}"

      if [ ! -x "$HERMES_BIN" ] && command -v hermes >/dev/null 2>&1; then
        HERMES_BIN="$(command -v hermes)"
      fi

      if [ ! -x "$HERMES_BIN" ]; then
        echo "error: 未找到 hermes，请先安装 Hermes，或设置 HERMES_BIN=/path/to/hermes。" >&2
        exit 127
      fi

      "$HERMES_BIN" mcp remove codegraph >/dev/null 2>&1 || true
      "$HERMES_BIN" mcp remove code-review-graph >/dev/null 2>&1 || true

      hermes_add() {
        printf 'y\n' | "$HERMES_BIN" mcp add "$@"
      }

      if [ -n "${CODEGRAPH_BIN:-}" ]; then
        hermes_add codegraph \
          --command sh \
          --env "CODEGRAPH_BIN=$CODEGRAPH_BIN" \
          --args "$PROJECT_ROOT/.claude/mcps/codegraph-mcp.sh"
      else
        hermes_add codegraph \
          --command sh \
          --args "$PROJECT_ROOT/.claude/mcps/codegraph-mcp.sh"
      fi

      if command -v code-review-graph >/dev/null 2>&1; then
        hermes_add code-review-graph \
          --command code-review-graph \
          --args mcp
      else
        echo "warning: 未找到 code-review-graph，跳过 Hermes 注册。"
      fi

      "$HERMES_BIN" mcp list
    SH

    HERMES_SETUP_SCRIPT = <<~'SH'
      #!/bin/sh

      set -eu

      SCRIPT_DIR="$(CDPATH= cd -- "$(dirname "$0")" && pwd)"
      HERMES_BIN="${HERMES_BIN:-$HOME/.local/bin/hermes}"
      HERMES_INSTALL_URL="${HERMES_INSTALL_URL:-https://raw.githubusercontent.com/NousResearch/hermes-agent/main/scripts/install.sh}"

      export PATH="$HOME/.local/bin:$PATH"

      find_hermes() {
        if [ -x "$HERMES_BIN" ]; then
          return 0
        fi

        if command -v hermes >/dev/null 2>&1; then
          HERMES_BIN="$(command -v hermes)"
          export HERMES_BIN
          return 0
        fi

        return 1
      }

      install_hermes() {
        if ! command -v curl >/dev/null 2>&1; then
          echo "error: 未找到 hermes，也未找到 curl，无法自动安装 Hermes。" >&2
          echo "请先安装 Hermes，或设置 HERMES_BIN=/path/to/hermes 后重试。" >&2
          exit 127
        fi

        echo "Hermes [install] $HERMES_INSTALL_URL"
        curl -fsSL "$HERMES_INSTALL_URL" | bash -s -- --skip-setup
      }

      if ! find_hermes; then
        install_hermes
      fi

      if ! find_hermes; then
        echo "error: Hermes 安装后仍未找到命令，请重新打开终端或设置 HERMES_BIN。" >&2
        exit 127
      fi

      "$HERMES_BIN" version || true
      sh "$SCRIPT_DIR/hermes-mcp.sh"
      "$HERMES_BIN" mcp test codegraph || true
    SH

