    def run(argv, project_directory: Dir.pwd)
      args = argv.dup
      command = args.shift || 'help'
      case command
      when 'help', '--help', '-h'
        show_help
      when 'init'
        init(project_directory, force: args.include?('--force'))
      when 'update'
        update(project_directory)
      when 'doctor'
        doctor(project_directory)
      when 'memory'
        memory(project_directory)
      when 'mcp'
        print_mcp_config(project_directory, target: args.shift)
      else
        abort_with("未知 podx ai 命令：#{command}")
      end
    end

    def show_help
      puts <<~TEXT
        Usage:
          podx ai init [--force]   生成 CLAUDE.md 和 .claude 项目结构
          podx ai update           更新 CodeGraph，并检查 Code Review Graph 改动影响
          podx ai doctor           检查 codegraph、code-review-graph、AI 文件状态
          podx ai memory           查看 Hermes 记忆使用说明和状态
          podx ai mcp [hermes|codex|claude]
                                  输出 Hermes / Codex / Claude Code MCP 配置说明
      TEXT
    end

    def init(project_directory, force: false)
      root = File.expand_path(project_directory)
      write_file(File.join(root, 'CLAUDE.md'), CLAUDE_TEMPLATE, force: force)
      write_claude_files(root, force: force)
      ensure_gitignore(root)

      puts "podx ai [init] #{root}"
    end

    def update(project_directory)
      root = File.expand_path(project_directory)
      script = File.join(root, '.claude', 'mcps', 'update-codegraph.sh')
      legacy_script = File.join(root, '.claude', 'mcp', 'update-codegraph.sh')
      script = legacy_script unless File.exist?(script)
      unless File.exist?(script)
        abort_with("未找到 #{script}，请先执行 podx ai init")
      end

      system('/bin/sh', script) || abort_with('podx ai update 执行失败')
    end

    def doctor(project_directory)
      root = File.expand_path(project_directory)
      puts "Project [ok] #{root}"
      print_file_status(File.join(root, 'CLAUDE.md'), 'CLAUDE.md')
      print_file_status(File.join(root, '.claude', 'commands', 'feature.md'), '.claude/commands')
      print_file_status(File.join(root, '.claude', 'rules', 'project.md'), '.claude/rules')
      print_file_status(File.join(root, '.claude', 'skills', 'feature.md'), '.claude/skills')
      print_file_status(File.join(root, '.claude', 'agents', 'ios-engineer.md'), '.claude/agents')
      print_file_status(File.join(root, '.claude', 'memory', 'README.md'), '.claude/memory')
      print_file_status(File.join(root, '.claude', 'mcps', 'claude-mcp.example.json'), '.claude/mcps')
      print_file_status(File.join(root, '.claude', 'mcps', 'hermes-mcp.sh'), '.claude/mcps/hermes-mcp.sh')
      print_file_status(File.join(root, '.claude', 'mcps', 'codegraph.sh'), '.claude/mcps/codegraph.sh')
      print_command_status('codegraph')
      print_command_status('code-review-graph')
      print_command_status('npx')
      print_command_status('hermes')
    end

    def memory(project_directory)
      root = File.expand_path(project_directory)
      readme = File.join(root, '.claude', 'memory', 'README.md')
      puts File.exist?(readme) ? File.read(readme) : memory_usage
      puts
      if find_command('hermes')
        system('hermes', 'memory', 'status') || true
      elsif File.executable?(File.expand_path('~/.local/bin/hermes'))
        system(File.expand_path('~/.local/bin/hermes'), 'memory', 'status') || true
      else
        puts 'warning: 未找到 hermes，无法读取 memory status。'
      end
    end

    def print_mcp_config(project_directory, target: nil)
      target = target.to_s.strip
      if target.empty?
        puts hermes_mcp_usage(project_directory)
        return
      end

      case target
      when 'hermes'
        puts hermes_mcp_usage(project_directory)
      when 'codex'
        puts mcp_example_content(project_directory, :codex)
      when 'claude', 'claude-code'
        puts mcp_example_content(project_directory, :claude)
      else
        abort_with("未知 MCP 类型：#{target}，可选 hermes、codex 或 claude")
      end
    end

    def write_claude_files(root, force:)
      claude_dir = File.join(root, '.claude')
      commands_dir = File.join(claude_dir, 'commands')
      rules_dir = File.join(claude_dir, 'rules')
      skills_dir = File.join(claude_dir, 'skills')
      agents_dir = File.join(claude_dir, 'agents')
      memory_dir = File.join(claude_dir, 'memory')
      mcp_dir = File.join(claude_dir, 'mcps')
      FileUtils.mkdir_p(commands_dir)
      write_file(File.join(claude_dir, 'README.md'), CLAUDE_README, force: force)
      CLAUDE_COMMAND_TEMPLATES.each do |name, content|
        write_file(File.join(commands_dir, name), content, force: force)
      end
      FileUtils.mkdir_p(rules_dir)
      CLAUDE_RULE_TEMPLATES.each do |name, content|
        write_file(File.join(rules_dir, name), content, force: force)
      end
      FileUtils.mkdir_p(skills_dir)
      CLAUDE_SKILL_TEMPLATES.each do |name, content|
        write_file(File.join(skills_dir, name), content, force: force)
      end
      FileUtils.mkdir_p(agents_dir)
      CLAUDE_AGENT_TEMPLATES.each do |name, content|
        write_file(File.join(agents_dir, name), content, force: force)
      end
      FileUtils.mkdir_p(memory_dir)
      CLAUDE_MEMORY_TEMPLATES.each do |name, content|
        write_file(File.join(memory_dir, name), content, force: force)
      end
      FileUtils.mkdir_p(mcp_dir)
      write_file(File.join(mcp_dir, 'README.md'), README, force: force)
      write_file(File.join(mcp_dir, 'claude-mcp.example.json'), CLAUDE_MCP_EXAMPLE, force: force)
      write_file(File.join(mcp_dir, 'codex-mcp.example.toml'), MCP_EXAMPLE, force: force)
      write_executable(File.join(mcp_dir, 'codegraph.sh'), CODEGRAPH_WRAPPER_SCRIPT, force: force)
      write_executable(File.join(mcp_dir, 'codegraph-mcp.sh'), CODEGRAPH_MCP_SCRIPT, force: force)
      write_executable(File.join(mcp_dir, 'hermes-mcp.sh'), HERMES_MCP_SCRIPT, force: force)
      write_executable(File.join(mcp_dir, 'setup-hermes-mcp.sh'), HERMES_SETUP_SCRIPT, force: force)
      write_executable(File.join(mcp_dir, 'init-codegraph.sh'), CODEGRAPH_INIT_SCRIPT, force: force)
      write_executable(File.join(mcp_dir, 'update-codegraph.sh'), CODEGRAPH_UPDATE_SCRIPT, force: force)
    end

    def ensure_gitignore(root)
      path = File.join(root, '.gitignore')
      existing = File.exist?(path) ? File.read(path) : ''

      if existing.include?('# AI / MCP local runtime state')
        puts "#{relative(path)} [exists]"
        return
      end

      content = existing.dup
      content << "\n" unless content.empty? || content.end_with?("\n")
      content << "\n" unless content.empty? || content.end_with?("\n\n")
      content << AI_GITIGNORE_RULES
      File.write(path, content)
      puts "#{relative(path)} [updated]"
    end

    def hermes_mcp_usage(project_directory)
      root = File.expand_path(project_directory)
      <<~TEXT
        # Hermes MCP
        # 团队默认通过 Hermes 统一管理 MCP，避免每个客户端单独维护配置。

        sh #{File.join(root, '.claude', 'mcps', 'hermes-mcp.sh')}
        hermes mcp list
        hermes mcp test codegraph
        hermes mcp test code-review-graph

        # 兼容参考：
        # podx ai mcp codex
        # podx ai mcp claude
      TEXT
    end

    def memory_usage
      <<~TEXT
        # Hermes Memory

        Hermes 内置记忆始终可用。外部记忆 provider 可选，可通过 `hermes memory setup` 配置。

        常用命令：

          hermes memory status
          hermes memory setup
