      Hermes 内置记忆始终可用，个人记忆保存在本机 Hermes home 中。工程只提交 `.claude/memory/` 下的记忆规范和模板，不提交个人记忆内容。

      ```bash
      podx ai memory
      hermes memory status
      hermes memory setup
      ```
