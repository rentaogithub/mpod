    CODEGRAPH_WRAPPER_SCRIPT = <<~'SH'
      #!/bin/sh

      set -eu

      CODEGRAPH_BIN="${CODEGRAPH_BIN:-}"

      node_major_version() {
        "$1" -v 2>/dev/null | sed 's/^v//' | cut -d. -f1
      }

      use_node22_dir() {
        if [ -n "${1:-}" ] && [ -x "$1/node" ] && [ "$(node_major_version "$1/node")" = "22" ]; then
          export PATH="$1:$PATH"
          return 0
        fi
        return 1
      }

      setup_node22() {
        if use_node22_dir "${NODE22_BIN:-}"; then
          return 0
        fi

        if command -v node >/dev/null 2>&1 && [ "$(node_major_version "$(command -v node)")" = "22" ]; then
          return 0
        fi

        for node_dir in \
          "$HOME"/.nvm/versions/node/v22.*/bin \
          "$HOME"/.volta/bin \
          "$HOME"/.asdf/shims \
          /opt/homebrew/opt/node@22/bin \
          /usr/local/opt/node@22/bin; do
          use_node22_dir "$node_dir" && return 0
        done

        echo "error: CodeGraph 需要 Node.js 22，请安装 Node 22 或设置 NODE22_BIN=/path/to/node22/bin。" >&2
        exit 1
      }

      setup_node22

      if [ -n "$CODEGRAPH_BIN" ] && [ -x "$CODEGRAPH_BIN" ]; then
        exec "$CODEGRAPH_BIN" "$@"
      fi

      if command -v codegraph >/dev/null 2>&1; then
        exec codegraph "$@"
      fi

      if command -v npx >/dev/null 2>&1; then
        exec npx -y @colbymchenry/codegraph "$@"
      fi

      echo "error: 未找到 codegraph 可执行文件，请先安装 CodeGraph runtime。" >&2
      exit 127
    SH

